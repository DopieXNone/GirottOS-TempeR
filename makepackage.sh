#!/bin/bash

set -e

# always run from the folder that contains this script
cd "$(dirname "$(readlink -f "$0")")"
ROOT=$(pwd)

PKGNAME=girottos-temper
PKGVER=0.1
PKGREL=1

# ── 1. normal build: checks GTK 4, Tela, X11, nvidia-smi → ./TempeR ───────────

./build.sh

# ── 2. Arch package of that executable ───────────────────────────────────────

echo
echo "======== TempeR Package ========"
echo

if ! command -v makepkg >/dev/null 2>&1; then
    echo "ERROR: makepkg not found."
    echo
    echo "makepkg is part of pacman: this script works on Arch Linux"
    echo "and Arch based systems only."
    exit 1
fi

for f in TempeR ../README.md ../LICENSE; do
    if [ ! -f "$f" ]; then
        echo "ERROR: $f not found."
        exit 1
    fi
done

# work folder, removed at the end (also when makepkg fails)
WORK=$(mktemp -d "${TMPDIR:-/tmp}/temper-pkg.XXXXXX")
trap 'rm -rf "$WORK"' EXIT

cp TempeR ../README.md ../LICENSE "$WORK/"

cat > "$WORK/temper.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Name=TempeR
GenericName=Hardware Monitor
Comment=Temperatures of processor, graphics card, disks, memory and system
Exec=TempeR
Icon=utilities-system-monitor
Terminal=false
Categories=System;Monitor;GTK;
Keywords=temperature;sensors;cpu;gpu;fan;monitor;overlay;
StartupNotify=true
StartupWMClass=com.girottos.TempeR
EOF

cat > "$WORK/PKGBUILD" <<EOF
# Maintainer: thelukyzz <uwulukyzz@gmail.com>
# Generated by makepackage.sh: packages the TempeR built by build.sh.

pkgname=$PKGNAME
pkgver=$PKGVER
pkgrel=$PKGREL
pkgdesc="GirottOS TempeR: temperature monitor with on-screen overlay and tray icon, Windows 10 File Explorer look (GTK 4, beta)"
arch=('x86_64')
url="https://github.com/DopieXNone/GirottOS-TempeR"
license=('Apache-2.0')
depends=('gtk4' 'glib2' 'pango' 'libx11')
optdepends=('tela-icon-theme: component, tray and status icons (AUR, otherwise emoji are shown)'
            'nvidia-utils: temperature and usage of NVIDIA GPUs (proprietary driver)'
            'hwdata: graphics card names from the pci.ids database')
options=('!debug')
source=('TempeR' 'temper.desktop' 'README.md' 'LICENSE')
sha256sums=('SKIP' 'SKIP' 'SKIP' 'SKIP')

package() {
  install -Dm755 TempeR "\$pkgdir/usr/bin/TempeR"
  install -Dm644 temper.desktop "\$pkgdir/usr/share/applications/com.girottos.TempeR.desktop"
  install -Dm644 README.md "\$pkgdir/usr/share/doc/\$pkgname/README.md"
  install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
EOF

# extra arguments go to makepkg, e.g. ./makepackage.sh -i to also install it
(cd "$WORK" && PKGDEST="$ROOT" makepkg -f "$@")

PKG="$PKGNAME-$PKGVER-$PKGREL-x86_64.pkg.tar.zst"

echo
echo "================================"
echo "Package complete!"
echo "Package: ./$PKG"
echo
echo "Install it with:"
echo "  sudo pacman -U ./$PKG"
echo "================================"
